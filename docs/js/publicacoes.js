const arquivosPublicacoesPSCPP = {};


// =====================================
// LOCALIZAR PUBLICAÇÃO
// =====================================

function obterPublicacao(codigoOuChave) {

    return publicacoesPSCPP.find(
        function (publicacao) {

            return (
                publicacao.id === codigoOuChave ||
                publicacao.chave === codigoOuChave
            );

        }
    );

}


// =====================================
// LISTAR POR DISCIPLINA
// =====================================

function listarPublicacoesPorDisciplina(
    disciplina
) {

    return publicacoesPSCPP.filter(
        function (publicacao) {

            return (
                publicacao.disciplina ===
                disciplina
            );

        }
    );

}


// =====================================
// PESQUISAR PUBLICAÇÕES
// =====================================

function pesquisarPublicacoes(termo) {

    const pesquisa =
        String(termo)
            .toLowerCase()
            .trim();

    if (!pesquisa) {

        return publicacoesPSCPP;

    }

    return publicacoesPSCPP.filter(
        function (publicacao) {

            const dados = [

                publicacao.id,
                publicacao.chave,
                publicacao.disciplina,
                publicacao.titulo,
                publicacao.autor,
                publicacao.tipo,
                publicacao.referencia,
                ...(publicacao.palavrasChave || [])

            ]
            .join(" ")
            .toLowerCase();

            return dados.includes(
                pesquisa
            );

        }
    );

}


// =====================================
// SELECIONAR PDF NO DISPOSITIVO
// =====================================

function selecionarPublicacao(
    codigoOuChave
) {

    const publicacao =
        obterPublicacao(
            codigoOuChave
        );

    if (!publicacao) {

        alert(
            "Publicação não cadastrada."
        );

        return;

    }


    const seletor =
        document.createElement(
            "input"
        );


    seletor.type = "file";

    seletor.accept =
        "application/pdf,.pdf";

    seletor.style.display =
        "none";


    seletor.addEventListener(
        "change",
        function (evento) {

            const arquivo =
                evento.target.files[0];


            if (!arquivo) {

                seletor.remove();

                return;

            }


            const nomeArquivo =
                arquivo.name
                    .toLowerCase();


            const arquivoPDF =
                arquivo.type ===
                    "application/pdf" ||
                nomeArquivo.endsWith(
                    ".pdf"
                );


            if (!arquivoPDF) {

                alert(
                    "Selecione um arquivo PDF."
                );

                seletor.remove();

                return;

            }


            arquivosPublicacoesPSCPP[
                publicacao.id
            ] = arquivo;


            abrirArquivoPublicacao(
                arquivo,
                publicacao.titulo
            );


            seletor.remove();

        }
    );


    document.body.appendChild(
        seletor
    );


    seletor.click();

}


// =====================================
// ABRIR PDF EM NOVA ABA
// =====================================

function abrirArquivoPublicacao(
    arquivo,
    tituloPublicacao
) {

    const enderecoTemporario =
        URL.createObjectURL(
            arquivo
        );


    const novaAba =
        window.open(
            enderecoTemporario,
            "_blank",
            "noopener,noreferrer"
        );


    if (!novaAba) {

        alert(
            "O navegador bloqueou a nova aba. " +
            "Permita a abertura de novas abas " +
            "para o Bridge Trainer."
        );


        URL.revokeObjectURL(
            enderecoTemporario
        );


        return;

    }


    setTimeout(
        function () {

            URL.revokeObjectURL(
                enderecoTemporario
            );

        },

        300000
    );

}


// =====================================
// ABRIR PUBLICAÇÃO
// =====================================

function abrirPublicacao(
    codigoOuChave
) {

    const publicacao =
        obterPublicacao(
            codigoOuChave
        );


    if (!publicacao) {

        alert(
            "Publicação não cadastrada."
        );

        return;

    }


    const arquivo =
        arquivosPublicacoesPSCPP[
            publicacao.id
        ];


    if (!arquivo) {

        selecionarPublicacao(
            publicacao.id
        );

        return;

    }


    abrirArquivoPublicacao(
        arquivo,
        publicacao.titulo
    );

}


// =====================================
// GERAR BLOCO HTML DA PUBLICAÇÃO
// =====================================

function gerarBlocoPublicacao(
    codigoOuChave
) {

    const publicacao =
        obterPublicacao(
            codigoOuChave
        );


    if (!publicacao) {

        return "";

    }


    const edicaoAno = [

        publicacao.edicao,
        publicacao.ano

    ]
    .filter(Boolean)
    .join(" — ");


    return `

        <article class="referencia-publicacao">

            <h4>
                📘 ${publicacao.titulo}
            </h4>

            <p>
                <strong>
                    Autor/Instituição:
                </strong>

                ${publicacao.autor}
            </p>

            ${
                edicaoAno
                    ? `

                        <p>
                            <strong>
                                Edição/Ano:
                            </strong>

                            ${edicaoAno}
                        </p>

                      `
                    : ""
            }

            <p>
                <strong>
                    Trecho indicado:
                </strong>

                ${publicacao.referencia}
            </p>

            <button
                type="button"
                class="botao-publicacao"
                onclick="
                    abrirPublicacao(
                        '${publicacao.id}'
                    )
                "
            >

                📖 Abrir publicação

            </button>

        </article>

    `;

}


// =====================================
// INSERIR REFERÊNCIAS NA AULA
// =====================================

function inserirReferenciasPublicacoes(
    idElemento,
    codigosPublicacoes
) {

    const elemento =
        document.getElementById(
            idElemento
        );


    if (!elemento) {

        console.warn(
            "Elemento de referências " +
            "não encontrado:",
            idElemento
        );

        return;

    }


    if (
        !Array.isArray(
            codigosPublicacoes
        )
    ) {

        console.warn(
            "A lista de publicações " +
            "deve ser um array."
        );

        return;

    }


    const blocos =
        codigosPublicacoes
            .map(
                gerarBlocoPublicacao
            )
            .join("");


    elemento.innerHTML =
        blocos;

        }
